export function formatMsg(template: string, vars: Record<string, string | number> = {}): string {
  return template.replace(/\{(\w+)\}/g, (_, key: string) => String(vars[key] ?? ''));
}

export function t(language: LanguageCode, key: I18nKey, vars?: Record<string, string | number>): string {
  const template = text[language][key] ?? text.en[key] ?? key;
  return vars ? formatMsg(template, vars) : template;
}

export const assistantNarrative = (language: LanguageCode, risk: RiskResponse): string => {
  const level = risk.risk_level === 'high' ? 'high' : 'low';

  if (language === 'si') {
    if (level === 'high') {
      return `ඉහළ අවදානමක් හඳුනාගෙන ඇත (${Math.round(risk.risk_score * 100)}%). 15 විනාඩිය ඇතුළත BP නැවත මැන Stage 2 පරීක්ෂණයට යොමු කරන්න.`;
    }
    return `අවදානම අඩු මට්ටමේ (${Math.round(risk.risk_score * 100)}%). 1-2 සති ඇතුළත නැවත පරීක්ෂණයක් සකසා නිතිපතා නිරීක්ෂණය කරගෙන යන්න.`;
  }

  if (language === 'ta') {
    if (level === 'high') {
      return `உயர் அபாயம் கண்டறியப்பட்டது (${Math.round(risk.risk_score * 100)}%). 15 நிமிடங்களில் BP மீண்டும் அளந்து Stage 2 மருத்துவ மதிப்பீட்டிற்கு உயர்த்தவும்.`;
    }
    return `அபாயம் குறைவு (${Math.round(risk.risk_score * 100)}%). 1-2 வாரங்களில் மீள் திரையிடல் செய்து வழக்கமான கண்காணிப்பை தொடரவும்.`;
  }

  if (level === 'high') {
    return `High-risk profile detected (${Math.round(risk.risk_score * 100)}%). Repeat BP in 15 minutes and escalate to Stage 2 hospital review.`;
  }
  return `Risk is currently low (${Math.round(risk.risk_score * 100)}%). Continue routine maternal monitoring and rescreen in 1-2 weeks.`;
};
